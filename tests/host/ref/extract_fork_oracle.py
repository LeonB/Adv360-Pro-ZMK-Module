#!/usr/bin/env python3
"""Regenerate fork_underglow.c: the Kinesis fork's underglow logic, extracted verbatim.

    python3 -I extract_fork_oracle.py [path/to/rgb_underglow.c]

Without an argument the file is downloaded (needs the GitHub CLI) from refil/zmk at the pinned
commit below, which is the revision the official Adv360-Pro-ZMK west.yml resolves
`adv360-z3.5-2` to. Functions are cut out by name with brace matching, so no hand-copied code.
"""
import base64
import re
import subprocess
import sys

SHA = "d93499bb877f2711989e6cbbe1feed9e9a792ca3"
PATH = "app/src/rgb_underglow.c"

if len(sys.argv) > 1:
    src = open(sys.argv[1]).read()
else:
    raw = subprocess.check_output(
        ["gh", "api", f"repos/refil/zmk/contents/{PATH}?ref={SHA}", "--jq", ".content"]
    )
    src = base64.b64decode(raw).decode()
lines = src.split("\n")


def block(start_pat, kind="func"):
    """Return the text of the construct whose first line matches start_pat."""
    for i, l in enumerate(lines):
        if re.match(start_pat, l):
            break
    else:
        sys.exit(f"not found: {start_pat}")
    depth, seen, out = 0, False, []
    for l in lines[i:]:
        out.append(l)
        depth += l.count("{") - l.count("}")
        seen = seen or "{" in l
        if seen and depth == 0:
            if kind == "struct" and not l.rstrip().endswith(";"):
                continue
            break
    if not out[0].startswith(("static", "#", "enum", "struct rgb_underglow_state")):
        out[0] = "static " + out[0]  # linkage only: lets several oracle objects link together
    return "\n".join(out)


def region(first_pat, last_pat, one_before=False):
    a = next(i for i, l in enumerate(lines) if re.match(first_pat, l))
    if one_before:
        a -= 1  # the `#if` line that opens the construct
    b = next(i for i, l in enumerate(lines) if i > a and re.match(last_pat, l))
    return "\n".join(lines[a : b + 1])


out = []
out.append(f'''/*
 * GENERATED by extract_fork_oracle.py - do not edit.
 *
 * Underglow, indicator and command logic of the Kinesis ZMK fork, extracted verbatim from
 *   refil/zmk  {PATH}  @ {SHA}
 *   (branch adv360-z3.5-2, the revision pinned by the official Adv360-Pro-ZMK west.yml)
 * Only the surrounding ZMK/Zephyr APIs are stubbed (fork_stubs.h), and `static` is added to the
 * public functions so that several oracle objects can be linked into one test. Used to check that the module
 * reproduces the official firmware pixel for pixel and command for command.
 */
#include "fork_stubs.h"

#define FORK_CAT2(a, b) a##b
#define FORK_CAT(a, b) FORK_CAT2(a, b)
#define FORK_NAME(n) FORK_CAT(FORK_PFX, n)

#define HUE_MAX 360
#define SAT_MAX 100
#define BRT_MAX 100

/* ---- begin verbatim ---- */
{block(r"^enum rgb_underglow_effect")}

{block(r"^struct rgb_underglow_state", "struct")}
/* ---- end verbatim ---- */

static const struct device *led_strip;
static struct led_rgb pixels[STRIP_NUM_PIXELS];
static struct rgb_underglow_state state;
static struct zmk_periph_led led_data;
static bool last_ble_state[2];
static bool triggered;
#if ZMK_BLE_IS_CENTRAL
static struct zmk_periph_led old_led_data;
#endif

/* Zephyr timer/work stand-ins for the on/off functions (see fork_stubs.h). */
static struct k_timer underglow_tick;
static struct k_work underglow_off_work;
#define K_WORK_DEFINE(name, fn) static int name##_unused
''')

for pat in [r"^static struct zmk_led_hsb hsb_scale_min_max", r"^static struct zmk_led_hsb hsb_scale_zero_max",
            r"^static struct led_rgb hsb_to_rgb"]:
    out.append("/* ---- begin verbatim ---- */\n" + block(pat) + "\n/* ---- end verbatim ---- */\n")

out.append("/* ---- begin verbatim: LED_RGB scaling ---- */\n"
           + region(r"^#define LED_RGB_SCALING_MULTIPLE", r"^\s*\}\)\s*$")
           + "\n/* ---- end verbatim ---- */\n")

out.append("/* ---- begin verbatim: central send, colours, layer map, blink, kinesis effect ---- */\n"
           + region(r"^static struct k_work_delayable led_update_work;", r"^static void zmk_rgb_underglow_effect_test", one_before=True)
           .rsplit("\nstatic void zmk_rgb_underglow_effect_test", 1)[0].rstrip()
           + "\n/* ---- end verbatim ---- */\n")

for pat in [r"^static void zmk_rgb_underglow_effect_solid", r"^static void zmk_rgb_underglow_effect_breathe",
            r"^static void zmk_rgb_underglow_effect_spectrum", r"^static void zmk_rgb_underglow_effect_swirl",
            r"^static void zmk_rgb_underglow_effect_test"]:
    out.append("/* ---- begin verbatim ---- */\n" + block(pat) + "\n/* ---- end verbatim ---- */\n")

out.append("/* ---- begin verbatim: battery effect ---- */\n"
           + region(r"^#define NUM_BATTERY_LEVELS", r"^static void zmk_rgb_underglow_effect_battery")
           .rsplit("\nstatic void zmk_rgb_underglow_effect_battery", 1)[0].rstrip() + "\n"
           + block(r"^static void zmk_rgb_underglow_effect_battery") + "\n/* ---- end verbatim ---- */\n")

out.append("/* ---- begin verbatim: state, commands ---- */\n")
out.append("static " + lines[next(i for i, l in enumerate(lines) if l.startswith("int zmk_rgb_underglow_save_state"))])
for pat in [r"^int zmk_rgb_underglow_on", r"^static void zmk_rgb_underglow_off_handler",
            r"^int zmk_rgb_underglow_off", r"^int zmk_rgb_underglow_calc_effect",
            r"^int zmk_rgb_underglow_select_effect", r"^int zmk_rgb_underglow_cycle_effect",
            r"^int zmk_rgb_underglow_toggle", r"^int zmk_rgb_underglow_set_hsb",
            r"^struct zmk_led_hsb zmk_rgb_underglow_calc_hue", r"^struct zmk_led_hsb zmk_rgb_underglow_calc_sat",
            r"^struct zmk_led_hsb zmk_rgb_underglow_calc_brt", r"^int zmk_rgb_underglow_change_hue",
            r"^int zmk_rgb_underglow_change_sat", r"^int zmk_rgb_underglow_change_brt",
            r"^int zmk_rgb_underglow_change_spd"]:
    out.append(block(pat) + "\n")
out.append("/* ---- end verbatim ---- */\n")

# Initial state: the struct initialiser from zmk_rgb_underglow_init (not the Zephyr parts around it).
init_start = next(i for i, l in enumerate(lines) if l.strip().startswith("state = (struct rgb_underglow_state){"))
init_end = next(i for i in range(init_start, len(lines)) if lines[i].strip() == "};")
init_blk = "\n".join(lines[init_start : init_end + 4])  # + led_data.indicators / on / effect lines
out.append("/* ---- begin verbatim: initial state (zmk_rgb_underglow_init) ---- */\nstatic void fork_init_state(void) {\n"
           + init_blk + "\n}\n/* ---- end verbatim ---- */\n")

# Tick dispatcher: the switch from zmk_rgb_underglow_tick without the strip update.
tick = block(r"^static void zmk_rgb_underglow_tick")
sw = tick[tick.index("switch"): tick.index("int err")].rstrip()
out.append("/* ---- begin verbatim: effect dispatcher (zmk_rgb_underglow_tick, minus the strip update) ---- */\n"
           "static void fork_dispatch_effect(void) {\n" + sw + "\n}\n/* ---- end verbatim ---- */\n")

out.append(r'''
/* ------------------------------------------------------------------------------------------ */
/* Test entry points                                                                          */

void FORK_NAME(reset)(void) {
    static const struct device dev;
    led_strip = &dev;
    memset(&state, 0, sizeof(state));
    memset(&led_data, 0, sizeof(led_data));
    memset(last_ble_state, 0, sizeof(last_ble_state));
#if ZMK_BLE_IS_CENTRAL
    memset(&old_led_data, 0, sizeof(old_led_data));
#endif
    memset(pixels, 0, sizeof(pixels));
    memset(&world, 0, sizeof(world));
    fork_init_state();
}

/* One 50 ms tick of the current effect, as the fork's timer would run it while the strip is on. */
void FORK_NAME(tick)(const struct stub_world *w, struct led_rgb out[3]) {
    world = *w;
#if !ZMK_BLE_IS_CENTRAL
    /* The peripheral gets layer + indicators pushed from the central instead of reading them. */
    led_data.layer = w->highest_layer;
    led_data.indicators = w->hid_indicators;
#endif
    fork_dispatch_effect();
    memcpy(out, pixels, sizeof(pixels));
}

void FORK_NAME(battery)(uint8_t soc, struct led_rgb out[3]) {
    world.soc = soc;
    zmk_rgb_underglow_effect_battery();
    memcpy(out, pixels, sizeof(pixels));
}

struct fork_state_view {
    uint16_t h;
    uint8_t s, b, speed, effect;
    uint16_t step;
    bool on;
};

void FORK_NAME(state)(struct fork_state_view *v) {
    v->h = state.color.h;
    v->s = state.color.s;
    v->b = state.color.b;
    v->speed = state.animation_speed;
    v->effect = state.current_effect;
    v->step = state.animation_step;
    v->on = state.on;
}

/* Commands, by the same names the `&rgb_ug` behavior calls them. Returns the fork's own result. */
enum fork_cmd {
    FORK_ON, FORK_OFF, FORK_TOGGLE, FORK_SELECT, FORK_CYCLE, FORK_SET_HSB,
    FORK_HUE, FORK_SAT, FORK_BRT, FORK_SPD,
};

int FORK_NAME(cmd)(enum fork_cmd c, int a, int b, int d) {
    switch (c) {
    case FORK_ON: return zmk_rgb_underglow_on();
    case FORK_OFF: return zmk_rgb_underglow_off();
    case FORK_TOGGLE: return zmk_rgb_underglow_toggle();
    case FORK_SELECT: return zmk_rgb_underglow_select_effect(a);
    case FORK_CYCLE: return zmk_rgb_underglow_cycle_effect(a);
    case FORK_SET_HSB: return zmk_rgb_underglow_set_hsb((struct zmk_led_hsb){.h = a, .s = b, .b = d});
    case FORK_HUE: return zmk_rgb_underglow_change_hue(a);
    case FORK_SAT: return zmk_rgb_underglow_change_sat(a);
    case FORK_BRT: return zmk_rgb_underglow_change_brt(a);
    case FORK_SPD: return zmk_rgb_underglow_change_spd(a);
    }
    return -1;
}
''')

open("fork_underglow.c", "w").write("\n".join(out))
print("wrote fork_underglow.c")
